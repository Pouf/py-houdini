"""Generate `src/py_houdini/data/node_types.py` from hython schema dumps.

    uv run python scripts/gen_node_types.py build/schema/houdini20.5.370.json

Pass the dumps oldest first: a newer version wins when two disagree. Dumps
come from `scripts/hython/dump_node_types.py`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

OUT = (
    Path(__file__).resolve().parent.parent
    / "src"
    / "py_houdini"
    / "data"
    / "node_types.py"
)


def main(paths: list[str]) -> None:
    file_parms: dict[str, dict[str, tuple[str, str]]] = {}
    child_categories: dict[str, str] = {}
    managers: dict[str, str] = {}
    versions = []
    for path in paths:
        dump = json.loads(Path(path).read_text(encoding="ascii"))
        versions.append(Path(path).stem.replace("houdini", ""))
        for name, info in dump["types"].items():
            if info["file_parms"]:
                file_parms[name] = {
                    parm: (parm_info["file_type"], parm_info["mode"])
                    for parm, parm_info in info["file_parms"].items()
                }
            if info["child_category"]:
                child_categories[name] = info["child_category"]
        managers.update(dump["managers"])

    lines = [
        '"""Houdini node types: file parameters, categories of their children, top-level networks.',
        "",
        f"Generated by `scripts/gen_node_types.py` from the node types of Houdini {', '.join(versions)}",
        "(`scripts/hython/dump_node_types.py`). Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        '# "<Category>/<type>" > parameter tuple (multiparm instances numbered with #)',
        '# > (file type, file chooser mode: "read", "write", "read_and_write" or "")',
        "FILE_PARMS: dict[str, dict[str, tuple[str, str]]] = {",
    ]
    for name, parms in sorted(file_parms.items()):
        lines.append(f"    {name!r}: {{")
        lines += [
            f"        {parm!r}: {info!r}," for parm, info in sorted(parms.items())
        ]
        lines.append("    },")
    lines += [
        "}",
        "",
        '# "<Category>/<type>" > category of the nodes it contains',
        "CHILD_CATEGORIES: dict[str, str] = {",
        *(
            f"    {name!r}: {category!r},"
            for name, category in sorted(child_categories.items())
        ),
        "}",
        "",
        "# Top-level network (/obj, /out...) > category of the nodes it contains",
        "MANAGERS: dict[str, str] = {",
        *(
            f"    {name!r}: {category!r},"
            for name, category in sorted(managers.items())
        ),
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        "wrote",
        OUT,
        len(file_parms),
        "types with file parameters,",
        len(child_categories),
        "networks",
    )


if __name__ == "__main__":
    main(sys.argv[1:])
